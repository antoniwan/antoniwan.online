import snapshot from './games.json';
import links from './game-links.json';

/** Where a game stands. `played` covers everything Antonio has picked up, from finished to opened once. `up-next` is the backlog and the games he is waiting for. */
export type GameStatus = 'playing' | 'played' | 'up-next';

/** How much an hour figure can be trusted, copied from the inventory's own logging conventions. */
export type HoursConfidence = 'tracked' | 'estimate' | 'floor' | 'unknown';

export interface GameHours {
  /** Point figure in hours, for sorting and bars. Null when unknown. Ranges use their midpoint here and keep the range in `display`. */
  value: number | null;
  /** Exactly as the source writes it: "4,190h", "~8,000h", "260h+", "121h 22m", "~2,000–3,000h". */
  display: string;
  confidence: HoursConfidence;
  /** Public label for the counter, such as "Steam via GOG Galaxy" or "In-game counter". Never a file path. */
  source: string | null;
}

export interface Game {
  /** Stable slug of the title. */
  id: string;
  title: string;
  /** Release year when the source records one. */
  year: number | null;
  /** Era from the backlog's decade sections, or derived from `year`. */
  decade: number | null;
  /** Store or console names: Steam, GOG, Xbox, PSN, PS5, Origin, Ubisoft Connect, PC. */
  platforms: string[];
  /** Genre heading from the backlog, emoji removed. */
  genre: string | null;
  status: GameStatus;
  hours: GameHours | null;
  /** Completion percent from a launcher. */
  progress: number | null;
  /** True for a game Antonio made (Uplift). */
  builtByMe?: boolean;
  href?: string;
}

export interface GamesSnapshot {
  /** ISO date the export ran. */
  exportedAt: string;
  lifetime: { low: number; high: number; confidence: 'estimate' };
  trackedFloorHours: number;
  /** Game ids in the current rotation, in display order. */
  nowPlaying: string[];
  /** Game ids Antonio is waiting for. */
  lookingForward: string[];
  games: Game[];
}

export const games = snapshot as GamesSnapshot;

export const gameStatusLabels: Record<GameStatus, string> = {
  playing: 'Playing',
  played: 'Played',
  'up-next': 'Up next',
};

export const hoursConfidenceLabels: Record<HoursConfidence, string> = {
  tracked: 'Tracked',
  estimate: 'Estimate',
  floor: 'At least',
  unknown: 'Unknown',
};

/** External links for a game, verified through Wikidata so both point at the same game. Generated by scripts/link-games.ts. */
export interface GameLink {
  /** Wikidata item id, such as "Q220767". */
  wikidata?: string;
  /** English Wikipedia article, or null when the item has none. */
  wikipedia: string | null;
  /** Steam store page, or null when the game is not sold there. */
  steam: string | null;
}

/** Lookup by game id. Only games with a confident match appear, so a missing key means no link. */
export const gameLinks: Record<string, GameLink> = links.links;
